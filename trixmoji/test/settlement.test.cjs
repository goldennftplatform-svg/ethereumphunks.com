const { test, before, after } = require('node:test')
const assert = require('node:assert/strict')
const { ethers } = require('ethers')
const { sandbox } = require('../lib/sandbox-chain.cjs')
const { approval } = require('../lib/approval.cjs')
let s
before(async () => { s = await sandbox() })
after(async () => { if (s) await s.close() })
const id = n => ethers.utils.keccak256(ethers.utils.toUtf8Bytes('test-ethscription-' + n))
const price = ethers.utils.parseEther('1')
async function listed(n) {
 const hash = id(n); await s.deposit(hash)
 await (await s.market.connect(s.seller).list(hash, price)).wait()
 return hash
}
test('deposit requires raw 32 bytes, zero ETH, and a five-block cooldown', async () => {
 await assert.rejects(s.seller.sendTransaction({ to: s.market.address, data: '0x1234' }))
 await assert.rejects(s.seller.sendTransaction({ to: s.market.address, data: id('badvalue'), value: 1 }))
 await (await s.seller.sendTransaction({ to: s.market.address, data: id('cooldown') })).wait()
 await assert.rejects(s.market.connect(s.seller).list(id('cooldown'), price))
 await s.mine(5)
 await (await s.market.connect(s.seller).cancel(id('cooldown'))).wait()
 assert.equal((await s.market.depositBlock(s.seller.address, id('cooldown'))).toString(), '0')
})
test('buy transfers to the buyer with previous-owner enforcement and splits 97.5/2.5', async () => {
 const hash = await listed(1)
 const auth = await s.approval({ id: hash, seller: s.seller.address, buyer: s.buyer.address })
 const sellerBefore = await s.market.credits(s.seller.address), royaltyBefore = await s.market.credits(s.creator.address)
 const receipt = await (await s.market.connect(s.buyer).buy(auth.approval, auth.signature, { value: price })).wait()
 const transfer = receipt.events.find(e => e.event === 'ethscriptions_protocol_TransferEthscriptionForPreviousOwner')
 assert.equal(transfer.args.previousOwner, s.seller.address)
 assert.equal(transfer.args.recipient, s.buyer.address)
 assert.equal(transfer.args.id, hash)
 assert.equal((await s.market.credits(s.seller.address)).sub(sellerBefore).toString(), ethers.utils.parseEther('0.975').toString())
 assert.equal((await s.market.credits(s.creator.address)).sub(royaltyBefore).toString(), ethers.utils.parseEther('0.025').toString())
 await assert.rejects(s.market.connect(s.buyer).buy(auth.approval, auth.signature, { value: price }))
})
test('wrong signer, buyer, price and stale listing authorizations cannot settle', async () => {
 const hash = await listed(2)
 const auth = await s.approval({ id: hash, seller: s.seller.address, buyer: s.buyer.address })
 const forged = await approval(s.market, s.buyer, { id: hash, seller: s.seller.address, buyer: s.buyer.address })
 await assert.rejects(s.market.connect(s.buyer).buy(forged.approval, forged.signature, { value: price }))
 await assert.rejects(s.market.connect(s.bidder).buy(auth.approval, auth.signature, { value: price }))
 await assert.rejects(s.market.connect(s.buyer).buy(auth.approval, auth.signature, { value: price.sub(1) }))
 await (await s.market.connect(s.seller).list(hash, price)).wait()
 await assert.rejects(s.market.connect(s.buyer).buy(auth.approval, auth.signature, { value: price }))
})
test('cancel returns the piece and invalidates a pending quote; redeposit cannot replay it', async () => {
 const hash = await listed(3)
 const auth = await s.approval({ id: hash, seller: s.seller.address, buyer: s.buyer.address })
 const receipt = await (await s.market.connect(s.seller).cancel(hash)).wait()
 assert.equal(receipt.events.find(e => e.event === 'ethscriptions_protocol_TransferEthscriptionForPreviousOwner').args.recipient, s.seller.address)
 await s.deposit(hash)
 await (await s.market.connect(s.seller).list(hash, price)).wait()
 await assert.rejects(s.market.connect(s.buyer).buy(auth.approval, auth.signature, { value: price }))
})
test('a forged potential deposit cannot overwrite another seller or buy without verifier', async () => {
 const hash = await listed(4)
 await s.deposit(hash, s.bidder)
 await (await s.market.connect(s.bidder).list(hash, 1)).wait()
 assert.equal((await s.market.listings(s.seller.address, hash)).price.toString(), price.toString())
 const forged = await approval(s.market, s.bidder, { id: hash, seller: s.bidder.address, buyer: s.buyer.address })
 await assert.rejects(s.market.connect(s.buyer).buy(forged.approval, forged.signature, { value: 1 }))
})
test('expired approvals fail', async () => {
 const hash = await listed(5)
 const auth = await s.approval({ id: hash, seller: s.seller.address, buyer: s.buyer.address })
 await s.advance(121)
 await assert.rejects(s.market.connect(s.buyer).buy(auth.approval, auth.signature, { value: price }))
})
test('auction bids refund via credits, extend near end, and settle only once', async () => {
 const hash = id(6); await s.deposit(hash)
 const auth = await s.approval({ id: hash, seller: s.seller.address, kind: 1, amount: price, duration: 3600 })
 await (await s.market.connect(s.seller).startAuction(auth.approval, auth.signature)).wait()
 const a = await s.market.auctions(s.seller.address, hash)
 await assert.rejects(s.market.connect(s.seller).cancel(hash))
 await assert.rejects(s.market.connect(s.seller).list(hash, price))
 await assert.rejects(s.market.connect(s.buyer).settle(s.seller.address, hash, a.nonce))
 await (await s.market.connect(s.buyer).bid(s.seller.address, hash, a.nonce, { value: price })).wait()
 await assert.rejects(s.market.connect(s.bidder).bid(s.seller.address, hash, a.nonce, { value: price }))
 const before = await s.market.credits(s.buyer.address)
 await s.advance(3500)
 await (await s.market.connect(s.bidder).bid(s.seller.address, hash, a.nonce, { value: ethers.utils.parseEther('1.05') })).wait()
 assert.equal((await s.market.credits(s.buyer.address)).sub(before).toString(), price.toString())
 assert.ok((await s.market.auctions(s.seller.address, hash)).end.gt(a.end))
 await s.advance(301)
 const receipt = await (await s.market.settle(s.seller.address, hash, a.nonce)).wait()
 assert.equal(receipt.events.find(e => e.event === 'ethscriptions_protocol_TransferEthscriptionForPreviousOwner').args.recipient, s.bidder.address)
 await assert.rejects(s.market.settle(s.seller.address, hash, a.nonce))
})
test('no-bid auction returns to seller and credits cannot be withdrawn twice', async () => {
 const hash = id(7); await s.deposit(hash)
 const auth = await s.approval({ id: hash, seller: s.seller.address, kind: 1, amount: price, duration: 3600 })
 await (await s.market.connect(s.seller).startAuction(auth.approval, auth.signature)).wait()
 await s.advance(3601)
 const receipt = await (await s.market.settle(s.seller.address, hash, auth.approval.nonce)).wait()
 assert.equal(receipt.events.find(e => e.event === 'ethscriptions_protocol_TransferEthscriptionForPreviousOwner').args.recipient, s.seller.address)
 const credit = await s.market.credits(s.seller.address)
 assert.ok(credit.gt(0))
 const before = await s.provider.getBalance(s.creator.address)
 await (await s.market.connect(s.seller).withdraw(s.creator.address)).wait()
 assert.equal((await s.provider.getBalance(s.creator.address)).sub(before).toString(), credit.toString())
 await assert.rejects(s.market.connect(s.seller).withdraw(s.creator.address))
})
